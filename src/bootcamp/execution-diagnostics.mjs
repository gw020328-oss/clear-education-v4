function one(error){
 let errorKind='NON_ERROR';
 try{if(types.isProxy(error))errorKind='OPAQUE';else if(types.isNativeError(error)){
  const p=Object.getPrototypeOf(error);errorKind=p===RuleError.prototype?'RULE_ERROR':p===TypeError.prototype?'TYPE_ERROR':p===RangeError.prototype?'RANGE_ERROR':p===Error.prototype?'ERROR':'NATIVE_ERROR';
 }}catch{errorKind='OPAQUE';}
 for(const key of ['code','message']){const v=own(error,key);if(typeof v==='string'&&codes.has(v))return {errorKind,code:v,codeBasis:key==='code'?'OWN_CODE':'FIXED_MESSAGE'};}
 return {errorKind,code:'UNCLASSIFIED',codeBasis:'REDACTED'};
}
export function executionErrorSummary(error){
 const causes=[],seen=new Set([error]);let next=own(error,'cause');
 while(next!==undefined&&causes.length<3&&!seen.has(next)){seen.add(next);causes.push(one(next));next=own(next,'cause');}
 return {...one(error),causes,causeChainTruncated:next!==undefined};
}
// A diagnostic failure must not mask the original exception or retry the action.
export function observeExecutionFailure(record,phase,error,details){try{record?.(phase,error,details);}catch{}}
export function createExecutionFailureLog(){
 const events=[],origin=performance.now();
 return {record(phase,error,details={}){
  if(events.length>=16)return;
  // All callers supply source-defined phase labels, never request fields.
  const entry={phase:phases.has(phase)?phase:'UNKNOWN_PHASE',...executionErrorSummary(error),atUnixMs:Date.now(),offsetMs:Math.max(0,performance.now()-origin),rejected:1,sendOutcome:phase==='BROADCAST'?'UNKNOWN':'NOT_INFERRED'};
  if(phases.has(details.subphase))entry.subphase=details.subphase;
  events.push(Object.freeze(entry));
 },snapshot:()=>structuredClone(events)};
}
